// Writes site/assets/droid-data.js: the output parameter names (and abbreviations) of every
// circuit, so the website's code highlighter colours inputs and outputs like the extension.
// Run after changing circuits/*.yaml:  node scripts/site-data.js
const fs = require("fs");
const path = require("path");
const yaml = require("js-yaml");
const root = path.join(__dirname, "..");
const outputs = {};
for (const f of fs.readdirSync(path.join(root, "circuits"))) {
  if (!f.endsWith(".yaml")) continue;
  const c = yaml.load(fs.readFileSync(path.join(root, "circuits", f), "utf8"));
  const names = new Set();
  for (const o of c.outputs || []) {
    names.add(o.name);
    if (o.abbr) names.add(o.abbr);
  }
  outputs[c.name] = [...names];
}
const js = "// Generated by scripts/site-data.js — do not edit.\nwindow.DROID_OUTPUTS = " + JSON.stringify(outputs) + ";\n";
fs.writeFileSync(path.join(root, "site/assets/droid-data.js"), js);
console.log("circuits:", Object.keys(outputs).length, "bytes:", js.length);
